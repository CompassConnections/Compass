        // android/app/google-services.json). Configuring without it traps, so a local build that
        // hasn't fetched it still runs — just without push.
        if Bundle.main.path(forResource: "GoogleService-Info", ofType: "plist") != nil {
            FirebaseApp.configure()
        } else {
            print("CompassApp: GoogleService-Info.plist missing — push notifications disabled")
        }
        return true
    }

